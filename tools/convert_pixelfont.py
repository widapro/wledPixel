#!/usr/bin/env python3
"""Convert PixelFonts' 8-row 3D BDF to the MD_MAX72XX column format.

Download the pinned BDF linked in the generated header, then run:
    python3 tools/convert_pixelfont.py /path/to/pixelfont_3d_5x5_thin.bdf
"""

import argparse
from pathlib import Path


REVISION = "344a6cfcd660b8546258485befb7576a47790d7d"
SOURCE = (
    f"https://github.com/mcer12/PixelFonts/blob/{REVISION}"
    "/bdf/pixelfont_3d_5x5_thin.bdf"
)
OUTPUT = Path(__file__).resolve().parents[1] / "lib/wledFont/PixelFont3D.h"


def read_glyphs(source):
    glyphs = {}
    for block in source.split("STARTCHAR ")[1:]:
        fields = block.splitlines()
        codepoint = int(next(line.split()[1] for line in fields
                             if line.startswith("ENCODING ")))
        advance = int(next(line.split()[1] for line in fields
                           if line.startswith("DWIDTH ")))
        width, height, x_offset, y_offset = map(int, next(
            line.split()[1:] for line in fields if line.startswith("BBX ")))
        top = 8 - height - y_offset
        columns = [0] * (advance - 1)  # Parola adds configurable character spacing.
        if not (0 <= top <= 8 - height and 0 <= x_offset
                and x_offset + width <= len(columns) <= 8):
            raise ValueError(f"U+{codepoint:04X} does not fit an 8-row font")
        start = fields.index("BITMAP") + 1
        rows = fields[start:fields.index("ENDCHAR")]
        if len(rows) != height:
            raise ValueError(f"U+{codepoint:04X} has an invalid bitmap height")
        for row_index, row in enumerate(rows):
            bits = int(row, 16)
            for column in range(width):
                if bits & (1 << (len(row) * 4 - 1 - column)):
                    columns[x_offset + column] |= 1 << (top + row_index)
        glyphs[codepoint] = columns
    return glyphs


def font_slots(glyphs):
    slots = [list(glyphs[ord("?")]) for _ in range(256)]
    for codepoint in range(32):
        slots[codepoint] = []
    for codepoint in range(32, 127):
        slots[codepoint] = glyphs[codepoint]
    slots[128] = glyphs[0x20AC]  # Euro, in the existing Wled font slot.
    # Existing application symbols: stock arrows, blinking clock separator,
    # and degrees for OWM/DS18B20 temperatures. These are Wled glyphs, not 3D.
    slots[24] = [8, 4, 126, 4, 8]
    slots[25] = [16, 32, 126, 32, 16]
    slots[160] = [0] * len(slots[ord(":")])
    slots[176] = [6, 9, 9, 6]
    return slots


def make_header(slots):
    lines = [
        "#pragma once", "", "#include <MD_MAX72xx.h>", "",
        "// PixelFonts pixelfont_3d_5x5_thin, Copyright (c) 2026 mcer12.",
        "// MIT License: see PixelFonts-LICENSE.txt in this directory.",
        f"// Source: {SOURCE}",
        "// Generated by tools/convert_pixelfont.py; do not edit the bitmap data.",
        "// Columns are left-to-right; bit 0 is the top row. Unsupported glyphs use '?'.",
        "// Slot 160 is a colon-width blank so blinking clocks keep the same width.",
        "const MD_MAX72XX::fontType_t pixelFont3D[] PROGMEM = {",
    ]
    for codepoint, columns in enumerate(slots):
        values = ", ".join([str(len(columns))]
                           + [f"0x{column:02x}" for column in columns])
        label = repr(chr(codepoint)) if 32 <= codepoint < 127 else ""
        lines.append(f"    {values}, // {codepoint} {label}".rstrip())
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bdf", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    glyphs = read_glyphs(args.bdf.read_text(encoding="utf-8"))
    args.output.write_text(make_header(font_slots(glyphs)), encoding="utf-8")


if __name__ == "__main__":
    main()
